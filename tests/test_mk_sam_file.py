"""Regression tests for mk_sam_file.py.

The expected outputs in tests/data/<site>/expected were generated by
mk_sam_file.py at commit 378bfd0 (before the pandas 3 compatibility changes)
running under pandas 2.2.3. The input files are real site templates:

- GW3-: Graafwater Formation, South Africa (Table_Mountain_Group). Southern
  hemisphere site with a mix of sun compass and magnetic compass only
  (IGRF corrected) samples and numeric sample names. The field shadow angles
  were read as core trend and have had 90 degrees added to convert them to
  core-plate strike (see sun_compass_correction.xlsx), as was done for the
  GW3- header files used for measurement.
- MF12-: Merced Formation, California (Merced_Formation). Northern hemisphere
  site with bedding orientations and alphanumeric sample names.

Run with:  python -m pytest tests
"""

import csv
import io
import os
import shutil
import subprocess
import sys

import pytest

REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(REPO_DIR, 'tests', 'data')
SITES = ['GW3-', 'MF12-']


def run_mk_sam_file(site, tmp_path):
    """Copy a site template into tmp_path and run mk_sam_file.py on it.

    Args:
        site (str): site id (name of the folder in tests/data).
        tmp_path (pathlib.Path): pytest temporary directory.

    Returns:
        str: path to the directory holding the generated files.
    """
    output_dir = tmp_path / site
    output_dir.mkdir()
    csv_path = output_dir / (site + '.csv')
    shutil.copy(os.path.join(DATA_DIR, site, 'input', site + '.csv'), csv_path)
    result = subprocess.run([sys.executable, 'mk_sam_file.py', str(csv_path), str(output_dir)],
                            cwd=REPO_DIR, capture_output=True, text=True)
    assert result.returncode == 0, result.stdout + result.stderr
    return str(output_dir)


def read_bytes(path):
    with open(path, 'rb') as f:
        return f.read()


def csv_rows_without_igrf_vector(path):
    """Read a rewritten site csv, dropping the calculated_IGRF column.

    The calculated_IGRF column is written as the repr of a list of numpy floats,
    which changes between numpy versions (e.g. '13.1' vs 'np.float64(13.1)'),
    so it is excluded; IGRF_local_dec (the declination that is used) is kept.
    """
    with open(path, newline='') as f:
        rows = list(csv.reader(io.StringIO(f.read().replace('\r\n', '\n'))))
    header_index = next(i for i, row in enumerate(rows) if row and row[0] == 'sample_name')
    igrf_column = rows[header_index].index('calculated_IGRF')
    return [row[:igrf_column] + row[igrf_column + 1:] if i >= header_index else row
            for i, row in enumerate(rows)]


@pytest.mark.parametrize('site', SITES)
def test_sam_and_sample_files_match_expected(site, tmp_path):
    """The .sam header and every sample file match the reference output exactly."""
    output_dir = run_mk_sam_file(site, tmp_path)
    expected_dir = os.path.join(DATA_DIR, site, 'expected')
    expected_files = [name for name in os.listdir(expected_dir)
                      if not name.endswith(('.csv', '.inp'))]
    assert site + '.sam' in expected_files
    for name in expected_files:
        assert read_bytes(os.path.join(output_dir, name)) == \
            read_bytes(os.path.join(expected_dir, name)), name


@pytest.mark.parametrize('site', SITES)
def test_inp_file_matches_expected(site, tmp_path):
    """The .inp file matches the reference output (path separator normalized)."""
    output_dir = run_mk_sam_file(site, tmp_path)
    expected = read_bytes(os.path.join(DATA_DIR, site, 'expected', site + '.inp'))
    generated = read_bytes(os.path.join(output_dir, site + '.inp'))
    assert generated.replace(b'.\\', b'./') == expected.replace(b'.\\', b'./')


@pytest.mark.parametrize('site', SITES)
def test_rewritten_csv_matches_expected(site, tmp_path):
    """The rewritten site csv with calculated fields matches the reference output."""
    output_dir = run_mk_sam_file(site, tmp_path)
    assert csv_rows_without_igrf_vector(os.path.join(output_dir, site + '.csv')) == \
        csv_rows_without_igrf_vector(os.path.join(DATA_DIR, site, 'expected', site + '.csv'))


def test_gw3_orientations():
    """Spot check GW3- reference values that were verified independently.

    Sun compass samples should give a sun-minus-magnetic declination close to
    the local field (about -24 to -26 degrees at Clanwilliam in May 2025), and
    magnetic-only samples are corrected by the IGRF declination.
    """
    with open(os.path.join(DATA_DIR, 'GW3-', 'expected', 'GW3-1'), newline='') as f:
        lines = f.read().split('\r\n')
    assert lines[0] == 'GW3- 1 sun compass orientation'
    strat_level, core_strike, core_dip, bedding_strike, bedding_dip, mass = lines[1].split()
    assert float(core_strike) == pytest.approx(147.7)
    assert float(core_dip) == pytest.approx(37.0)
    # magnetic core strike was 173, so the implied declination is -25.3
    assert float(core_strike) - 173 == pytest.approx(-25.3, abs=0.05)

    with open(os.path.join(DATA_DIR, 'GW3-', 'expected', 'GW3-9'), newline='') as f:
        lines = f.read().split('\r\n')
    assert lines[0] == 'GW3- 9 mag compass orientation (IGRF corrected)'
    # magnetic core strike of 196 corrected by an IGRF declination of -23.5
    assert float(lines[1].split()[1]) == pytest.approx(172.5)
